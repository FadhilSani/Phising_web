rec_knn  = recall_score(y_test, y_pred_knn, pos_label=1)
f1_knn   = f1_score(y_test, y_pred_knn, pos_label=1)
auc_knn  = roc_auc_score(y_test, y_prob_knn)

# Cross-validation 5-fold untuk KNN
