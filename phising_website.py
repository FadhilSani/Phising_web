print(f'Precision : {prec_knn:.4f}')
print(f'Recall    : {rec_knn:.4f}')
print(f'F1-Score  : {f1_knn:.4f}')
print(f'AUC-ROC   : {auc_knn:.4f}')
print(f'CV (5-fold): {cv_scores_knn.mean():.4f} +/- {cv_scores_knn.std():.4f}')

# Confusion matrix KNN
cm_knn = confusion_matrix(y_test, y_pred_knn)
tn_knn, fp_knn, fn_knn, tp_knn = cm_knn.ravel()

plt.figure(figsize=(7, 6))
sns.heatmap(
    cm_knn, annot=True, fmt='d', cmap='Blues',
    xticklabels=['Phishing (0)', 'Legitimate (1)'],
    yticklabels=['Phishing (0)', 'Legitimate (1)'],
    linewidths=1, linecolor='white',
    annot_kws={'size': 15, 'weight': 'bold'}
)
plt.title(f'Confusion Matrix — KNN (K={best_k})\nAccuracy: {acc_knn:.4f}', fontweight='bold', fontsize=13)
plt.xlabel(f'Predicted Label\nTP={tp_knn} | TN={tn_knn} | FP={fp_knn} | FN={fn_knn}', fontsize=10)
plt.ylabel('True Label', fontsize=10)
