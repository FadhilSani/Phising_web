# Library standar dan visualisasi
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import warnings
warnings.filterwarnings('ignore')

# IMPORT XGBOOST SECARA LENGKAP
import xgboost as xgb
from xgboost import XGBClassifier

# Sumber dataset
from ucimlrepo import fetch_ucirepo

# Preprocessing dan splitting
from sklearn.model_selection import train_test_split, cross_val_score, StratifiedKFold
from sklearn.preprocessing import StandardScaler

# Balancing data (SMOTE)
from imblearn.over_sampling import SMOTE

# Model klasifikasi
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from sklearn.ensemble import GradientBoostingClassifier
from xgboost import XGBClassifier

# Metrik evaluasi
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    f1_score, roc_auc_score, roc_curve,
    confusion_matrix, classification_report
)

"""## 2. Load Dataset dari UCI ML Repository"""

# Mengambil dataset Phishing Websites langsung dari UCI ML Repository (ID: 327)
phishing = fetch_ucirepo(id=327)

# Pisahkan fitur (X) dan target (y)
X = phishing.data.features
y = phishing.data.targets.squeeze()  # Konversi ke Series 1D

print(f'Dataset berhasil dimuat dari UCI ML Repository!')
print(f'Shape X: {X.shape}')
print(f'Shape y: {y.shape}')
X.head()

"""## 3. Penyesuaian Kelas Target (2 Kelas: 0 dan 1)

Dataset asli memiliki nilai target: `-1` (Phishing), `0` (Suspicious), `1` (Legitimate).  
Digabung menjadi 2 kelas biner:
- **0** → Phishing (gabungan kelas `-1` dan `0` / Suspicious)
- **1** → Legitimate

Alasan Mengapa dijadiin 2 aja yaitu:
- Sampel kelas suspicious relatif sedikit jadi kurang representatif untuk dilatih sebagai kelas terpisah
- Konteks keamanan jadi website suspicious tetap berpotensi berbahaya, sehingga lebih aman dikategorikan sebagai phishing
- Klasifikasi biner lebih sederhana jadi model lebih stabil dan proses evaluasi lebih mudah
"""

y = y.apply(lambda v: 0 if v <= 0 else 1)

print('Distribusi kelas setelah penyesuaian:')
vc = y.value_counts()
print(f'  Phishing   (0) : {vc[0]:,} ({vc[0]/len(y)*100:.1f}%)')
print(f'  Legitimate (1) : {vc[1]:,} ({vc[1]/len(y)*100:.1f}%)')

"""## 4. Eksplorasi Data (EDA)"""

# Informasi umum dataset sebelum balancing
print('=== INFO DATASET ===')
print(f'Jumlah Fitur   : {X.shape[1]}')
print(f'Jumlah Sampel  : {X.shape[0]:,}')
print(f'Missing Values : {X.isnull().sum().sum()}')

# Visualisasi distribusi kelas dan korelasi fitur dengan target
df_eda = X.copy()
df_eda['Result'] = y.values

fig, axes = plt.subplots(1, 2, figsize=(12, 5))
fig.suptitle('Distribusi Dataset (Sebelum Balancing)', fontsize=14, fontweight='bold')

# Pie chart distribusi kelas
colors = ['#e74c3c', '#2ecc71']
labels = ['Phishing (0)', 'Legitimate (1)']
sizes  = [vc[0], vc[1]]
axes[0].pie(sizes, labels=labels, colors=colors, autopct='%1.1f%%',
            startangle=90, wedgeprops={'edgecolor': 'white', 'linewidth': 2})
axes[0].set_title('Distribusi Kelas Target')

# Bar chart korelasi fitur dengan target (top 15)
corr = df_eda.corr()['Result'].drop('Result').abs().sort_values(ascending=True).tail(15)
axes[1].barh(corr.index, corr.values, color=plt.cm.RdYlGn(corr.values), edgecolor='white')
axes[1].set_title('Top 15 Fitur vs Target (|Korelasi|)')
axes[1].set_xlabel('|Korelasi|')
axes[1].set_facecolor('#f9f9f9')

plt.tight_layout()
plt.show()

"""## 5. Balancing Data dengan SMOTE"""

# Terapkan SMOTE untuk menyeimbangkan kelas sebelum splitting
smote = SMOTE(random_state=42)
X_balanced, y_balanced = smote.fit_resample(X, y)

# Tampilkan distribusi kelas setelah balancing
vc_bal = pd.Series(y_balanced).value_counts()
print('Distribusi kelas setelah SMOTE:')
print(f'  Phishing   (0) : {vc_bal[0]:,} ({vc_bal[0]/len(y_balanced)*100:.1f}%)')
print(f'  Legitimate (1) : {vc_bal[1]:,} ({vc_bal[1]/len(y_balanced)*100:.1f}%)')
print(f'Total sampel     : {len(y_balanced):,}')

"""## 6. Preprocessing"""

# Split data 80/20 dengan stratifikasi setelah balancing
X_train, X_test, y_train, y_test = train_test_split(
    X_balanced, y_balanced, test_size=0.2, random_state=42, stratify=y_balanced
)

# Scaling fitur (diperlukan oleh KNN dan SVM)
scaler = StandardScaler()
X_train_sc = scaler.fit_transform(X_train)  # Fit hanya pada data train
X_test_sc  = scaler.transform(X_test)       # Transform data test dengan scaler yang sama

print(f'Data Train : {X_train.shape[0]:,} sampel')
print(f'Data Test  : {X_test.shape[0]:,} sampel')

"""---
# Model 1: Random Forest (RF)

## 7. Training Model Random Forest
"""

# Melatih Random Forest menggunakan data asli (tanpa scaling)
rf = RandomForestClassifier(n_estimators=100, random_state=42)
rf.fit(X_train, y_train)

# Prediksi label dan probabilitas kelas positif (1 = Legitimate)
y_pred_rf = rf.predict(X_test)
y_prob_rf = rf.predict_proba(X_test)[:, 1]

print('Model Random Forest selesai dilatih!')
print(f'n_estimators : 100')
print(f'random_state : 42')

"""## 8. Evaluasi Model Random Forest"""

# Hitung metrik evaluasi untuk Random Forest
acc_rf  = accuracy_score(y_test, y_pred_rf)
prec_rf = precision_score(y_test, y_pred_rf, pos_label=1)
rec_rf  = recall_score(y_test, y_pred_rf, pos_label=1)
f1_rf   = f1_score(y_test, y_pred_rf, pos_label=1)
auc_rf  = roc_auc_score(y_test, y_prob_rf)

# Cross-validation 5-fold untuk estimasi performa yang lebih stabil
cv_rf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
cv_scores_rf = cross_val_score(rf, X_train, y_train, cv=cv_rf, scoring='accuracy')

print('HASIL EVALUASI RANDOM FOREST')
print(f'Accuracy  : {acc_rf:.4f} ({acc_rf*100:.2f}%)')
print(f'Precision : {prec_rf:.4f}')
print(f'Recall    : {rec_rf:.4f}')
print(f'F1-Score  : {f1_rf:.4f}')
print(f'AUC-ROC   : {auc_rf:.4f}')
print(f'CV (5-fold): {cv_scores_rf.mean():.4f} +/- {cv_scores_rf.std():.4f}')

# Confusion matrix Random Forest
cm_rf = confusion_matrix(y_test, y_pred_rf)
tn_rf, fp_rf, fn_rf, tp_rf = cm_rf.ravel()

plt.figure(figsize=(7, 6))
sns.heatmap(
    cm_rf, annot=True, fmt='d', cmap='Greens',
    xticklabels=['Phishing (0)', 'Legitimate (1)'],
    yticklabels=['Phishing (0)', 'Legitimate (1)'],
    linewidths=1, linecolor='white',
    annot_kws={'size': 15, 'weight': 'bold'}
)
plt.title(f'Confusion Matrix — Random Forest\nAccuracy: {acc_rf:.4f}', fontweight='bold', fontsize=13)
plt.xlabel(f'Predicted Label\nTP={tp_rf} | TN={tn_rf} | FP={fp_rf} | FN={fn_rf}', fontsize=10)
plt.ylabel('True Label', fontsize=10)
plt.tight_layout()
plt.show()

# ROC Curve Random Forest
fpr_rf, tpr_rf, _ = roc_curve(y_test, y_prob_rf, pos_label=1)

plt.figure(figsize=(8, 6))
plt.plot(fpr_rf, tpr_rf, color='#27ae60', lw=2, label=f'RF (AUC = {auc_rf:.4f})')
plt.plot([0, 1], [0, 1], 'k--', lw=1.5, label='Random Classifier')
plt.fill_between(fpr_rf, tpr_rf, alpha=0.1, color='#27ae60')
plt.xlim([0.0, 1.0])
plt.ylim([0.0, 1.02])
plt.xlabel('False Positive Rate (FPR)', fontsize=12)
plt.ylabel('True Positive Rate (TPR)', fontsize=12)
plt.title('ROC Curve — Random Forest', fontsize=14, fontweight='bold')
plt.legend(loc='lower right', fontsize=11)
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# Fitur paling berpengaruh dalam keputusan Random Forest (top 10)
importances = rf.feature_importances_
feat_imp = pd.Series(importances, index=X.columns).sort_values(ascending=False)

print('Top 10 Feature Importances:')
print(feat_imp.head(10))

feat_imp.head(10).plot(kind='bar', color='#27ae60', figsize=(10, 5))
plt.title('Top 10 Feature Importance — Random Forest', fontsize=13, fontweight='bold')
plt.xlabel('Fitur')
plt.ylabel('Importance')
plt.xticks(rotation=45, ha='right')
plt.tight_layout()
plt.show()

# Laporan klasifikasi lengkap per kelas
print('CLASSIFICATION REPORT — Random Forest')
print(classification_report(
    y_test, y_pred_rf,
    target_names=['Phishing (0)', 'Legitimate (1)']
))

# Ringkasan hasil Random Forest
print('=' * 48)
print('     RINGKASAN HASIL — Random Forest (RF)    ')
print('=' * 48)
print(f'Accuracy  : {acc_rf:.4f} ({acc_rf*100:.2f}%)')
print(f'Precision : {prec_rf:.4f}')
print(f'Recall    : {rec_rf:.4f}')
print(f'F1-Score  : {f1_rf:.4f}')
print(f'AUC-ROC   : {auc_rf:.4f}')
print(f'CV Mean   : {cv_scores_rf.mean():.4f} +/- {cv_scores_rf.std():.4f}')
print('-' * 48)
print(f'TP : {tp_rf}  |  TN : {tn_rf}')
print(f'FP : {fp_rf}  |  FN : {fn_rf}')
print('=' * 48)

"""---
# Model 2: K-Nearest Neighbors (KNN)

## 9. Mencari Nilai K Optimal
"""

# Mencari nilai K terbaik dengan cross-validation pada data yang sudah di-scale
k_range = range(2, 11)
k_scores = []

for k in k_range:
    knn_tmp = KNeighborsClassifier(n_neighbors=k)
    scores = cross_val_score(knn_tmp, X_train_sc, y_train, cv=5, scoring='accuracy')
    k_scores.append(scores.mean())
    print(f'K={k:2d} -> CV Accuracy: {scores.mean():.4f}')

# Pilih K dengan akurasi CV tertinggi
best_k = list(k_range)[k_scores.index(max(k_scores))]
print(f'\nK terbaik: {best_k} (Accuracy: {max(k_scores):.4f})')

# Visualisasi perubahan akurasi terhadap nilai K
plt.figure(figsize=(10, 5))
plt.plot(k_range, k_scores, marker='o', color='#3498db', linewidth=2, markersize=7)
plt.axvline(x=best_k, color='#e74c3c', linestyle='--', linewidth=1.5, label=f'K terbaik = {best_k}')
plt.scatter([best_k], [max(k_scores)], color='#e74c3c', s=100, zorder=5)
plt.title('Pemilihan Nilai K Optimal', fontsize=14, fontweight='bold')
plt.xlabel('Nilai K')
plt.ylabel('CV Accuracy')
plt.xticks(k_range)
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

"""## 10. Training Model KNN"""

# Melatih KNN menggunakan data yang sudah discale dan nilai K terbaik
